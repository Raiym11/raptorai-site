    i = line_with(lines, "<h1>")
    lines[i] = f'    <h1>{n["h1"]}</h1>'
    i = line_with(lines, '<p class="hero-sub">')
    lines[i] = f'    <p class="hero-sub">{n["sub"]}</p>'

    # --- возможности ------------------------------------------------------
