    lines[i] = '<body class="svc" style="--pacc:#00D4FF;--pacc2:#8C7BFF">'
    i = line_with(lines, '<section class="hero page-hero hx hx-brand"')
    lines[i] = '<section class="hero page-hero hx" style="position:relative;z-index:1;--acc:#00D4FF;--acc2:#8C7BFF">'
    i = line_with(lines, 'data-scene="chatgpt"')
    lines[i] = '  <div class="h3d" data-scene="agent" aria-hidden="true"></div>'

    # --- hero -------------------------------------------------------------
    i = line_with(lines, '<div class="crumbs">')
    lines[i] = (f'    <div class="crumbs"><a href="/">RaptorAI</a> / '
                f'<a href="/ai-agent-dlya-biznesa.html">ИИ-агент для бизнеса</a> / {n["crumb"]}</div>')
    i = line_with(lines, '<div class="hero-badge">')
